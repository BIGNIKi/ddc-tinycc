#!/bin/sh
# Общая часть веток A и B схемы DDC: окружение, флаги configure и функция сборки build().
#
# Этот файл НЕ запускают напрямую — его ПОДКЛЮЧАЮТ в начале других скриптов строкой:
#   . /work/build-common.sh
# (подключают build-branchA.sh — ветка A, и build-branchB.sh — ветка B).
#
# Зачем вынесено отдельно: флаги и логика сборки должны быть ОДИНАКОВЫМИ для обеих
# веток. Если бы они жили в двух файлах, их легко было бы случайно рассинхронить,
# и тогда A2 и B2 разошлись бы не из-за закладки, а из-за разницы в настройках.

# всё происходит внутри контейнера, но на монтированной папке work.
SRC=/work/input/tcc-mob.tar
OUT=/work/out
mkdir -p "$OUT"

# Общие флаги configure под musl-окружение образа. В функции build они передаются
# в ./configure (компилятор --cc подставляется отдельно: в ветке A это gcc/наш tcc,
# в ветке B — Alpine-gcc/наш tcc).
# Файл configure - из репозитория tinycc (https://github.com/TinyCC/tinycc)
# через configure можно настроить: под какую ОС собирать, под какую архитектуру процессора, какую libc (glibc, musl) использовать и т.д.
# В makefile лезть не нужно, достаточно настроить configure.
# --sysincludepaths=/x86_64/usr/include: где искать системные заголовки (stdio.h и т.д.)
# --libpaths=/x86_64/usr/lib:/x86_64/lib: где искать библиотеки (libc, libtcc1.a). То есть реализации заголовков.
# --crtprefix=/x86_64/usr/lib: где взять стартовые файлы программы (crt1.o, crti.o, crtn.o). То есть это точка входа _start, которая запускается ещё до main; а также логика, которая выполняется после main.
# 	В будущем, эти файлы будут "приклеиваться" к программам, которые tinycc собирает. К самому tinycc это тоже будет "приклеено" силами компирятора, на котором его собирают.
# --elfinterp=/lib/ld-musl-x86_64.so.1: какой динамический загрузчик будут использовать собранные программы при запуске (musl-загрузчик)
# 	Он будет запускаться каждый раз до точки входа _start. Его задача: подтянуть нужные библиотеки (libc), расставить адреса (чтобы printf указывал на реальный код в libc), и только потом передать управление в программу.
# 	В собранном бинарнике tinycc будет так, и во всех будущих собранных им программах будет также.
# Отключаем ненужное (конфликтует с musl, для нас не требуется):
# --config-bcheck=no: без проверки границ массивов. В tinycc можно сделать защиту: в скомпилированных им программах будут добавлятся проверки. Потом при падениях приложения легче понять, почему оно упало. Мы это отключили, т.к. под musl не собирается.
# --config-backtrace=no: без трассировки стека. Красивый список при падении приложения: кто кого вызывал. Не собирается под musl.
CONF="--sysincludepaths=/x86_64/usr/include \
  --libpaths=/x86_64/usr/lib:/x86_64/lib \
  --crtprefix=/x86_64/usr/lib \
  --elfinterp=/lib/ld-musl-x86_64.so.1 \
  --config-bcheck=no --config-backtrace=no"

# Использовать так:
# build <компилятор-для-сборки> <куда-положить-готовый-tcc>
build() {
  # папка tmp сразу есть в контейнере
  # rm -rf tcc — чистим распаковку от прошлого захода ф-ии build, чтобы собирать с нуля
  # (tar xf "$SRC") распаковываем архив с исходниками tinycc. В tmp появится папка tcc
  cd /tmp && rm -rf tcc && tar xf "$SRC" && cd tcc

  # (find . -type f) - находим все файлы, рекурсивно в подпапках тоже
  # (-exec ... {} +) - для всех файлов выполнить команду
  # (sed -i 's/\r$//') - сама команда для каждого файла (убирает виндовые концы строк)
  # 2>/dev/null (ошибки не выводить)
  find . -type f -exec sed -i 's/\r$//' {} + 2>/dev/null

  # --cc="$1": каким компилятором собирать (1-й заход — gcc, 2-й заход — наш же tcc с 1-го)
  sh ./configure --cc="$1" $CONF

  # собираем сам компилятор
  # P.S. make тут разный: в ветке A — из доверенной цепочки, в ветке B — от Alpine.
  # Для DDC это не важно: make лишь запускает команды компиляции, в байты tcc он
  # ничего не вкладывает (на результат влияют --cc и окружение /x86_64, а не make).
  make tcc

  # tcov.o - конфликтует с musl, не собирается. Поэтому вырезаем его из сборки.
  # Он был нужен, чтобы замерять покрытие кода: какие строки исполнялись, какие нет.
  sed -i 's/\btcov.o\b//g' lib/Makefile    # tcov конфликтует с musl, он не нужен

  # одного компилятора tinycc мало, нужна ещё библиотека libtcc1.a.
  # У gcc ситуация аналогичная, он таскает с собой libgcc. Можно почитать в интернете.
  make 2>/dev/null                         # собирает libtcc1.a и всё остальное, что не собрали ранее

  # проверяем, собрался ли libtcc1.a. Если нет, пишем ошибку и останавливаем скрипт
  [ -f libtcc1.a ] || { echo "libtcc1.a не собралась"; exit 1; }

  # т.к. ранее мы указали --libpaths=/x86_64/usr/lib:/x86_64/lib
  # tcc будет искать там libtcc1.a. Но сейчас его там нет.
  # Копируем туда собранный libtcc1.a
  cp -f libtcc1.a /x86_64/usr/lib/         # tcc ищет её в библиотечном пути
  cp -f tcc "$2"                           # сохраняем готовый компилятор ($2 внутри /work/out)
}
