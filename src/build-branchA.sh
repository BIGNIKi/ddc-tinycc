#!/bin/sh
# Ветка A схемы DDC (доверенная). Сборка tinycc доверенным gcc (A1) и сборка
# этим A1 своих же исходников (A2).
#
#   ШАГ 1: A1 = доверенный gcc собирает tinycc
#          (проверяем, что gcc собирает рабочий tinycc под musl)
#   ШАГ 2: наш доверенный tcc (A1) собирает свои исходники
#          (проверяем, что tinycc умеет собрать сам себя: A1 -> A2)
#
# Запускается ВНУТРИ контейнера trusted-toolchain.
# Ожидаем в /work/input (папку /work монтируем в контейнер):
#   tcc-mob.tar  — исходник tinycc (как достать — см. README, пункт «Достать чистый исходник tinycc»)
#   hello.c      — тестовая программа
# Готовые бинарники кладём в /work/out (A1, A2) — чтобы можно было посмотреть с хоста.

# Подключаем общую часть: SRC (исходники tinycc), OUT (папка, куда упадут собранные компиляторы), флаги CONF (вся конфигурация сборки компиляторов) и функцию build().
# (тот же файл подключает и ветка B — build-branchB.sh)
. /work/src/utils/build-common.sh

echo "=== ШАГ 1: доверенный gcc собирает tinycc (A1) ==="
build gcc "$OUT/tcc-A1"

echo "=== ШАГ 2: A1 собирает тот же tinycc — самосборка (A2) ==="
build "$OUT/tcc-A1" "$OUT/tcc-A2"

echo "=== проверка, что A2 рабочий ==="
"$OUT/tcc-A2" -v
"$OUT/tcc-A2" /work/input/hello.c -o /tmp/hello && /tmp/hello

echo "=== контрольные суммы ==="
sha256sum "$OUT/tcc-A1" "$OUT/tcc-A2"
